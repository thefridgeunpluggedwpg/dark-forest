// v0.30: picture water mask — 512x512 bits, 1 = water in Kyler's reference picture (far map), 0 = land. Decoded once per World.
function picWaterMask() {
  const raw = atob(PICWATER_B64), out = new Uint8Array(W * D);
  for (let i = 0; i < raw.length; i++) { const by = raw.charCodeAt(i); for (let b = 0; b < 8; b++) { const k = i * 8 + b; if (k < out.length && (by & (128 >> b))) out[k] = 1; } }
  // outer sea = water connected to the border; inland water = lakes
  const sea = new Uint8Array(W * D), stack = [];
  for (let x = 0; x < W; x++) for (const z of [0, D - 1]) if (out[z * W + x]) { sea[z * W + x] = 1; stack.push(z * W + x); }
  for (let z = 0; z < D; z++) for (const x of [0, W - 1]) if (out[z * W + x] && !sea[z * W + x]) { sea[z * W + x] = 1; stack.push(z * W + x); }
  while (stack.length) { const k = stack.pop(), x = k % W, z = (k / W) | 0; for (const [dx, dz] of [[1,0],[-1,0],[0,1],[0,-1]]) { const nx = x + dx, nz = z + dz; if (nx >= 0 && nx < W && nz >= 0 && nz < D) { const nk = nz * W + nx; if (out[nk] && !sea[nk]) { sea[nk] = 1; stack.push(nk); } } } }
  return { water: out, sea };
}
// v0.13: biome grid painted from the far map (see tools/biomemask.py). Returns per-tile biome code + distance-inside-mountain for heights.
function picBiomeMask() {
  const raw = atob(BIOME_B64), m = new Uint8Array(W * D); let k = 0;
  for (let i = 0; i + 1 < raw.length; i += 2) { const v = raw.charCodeAt(i), n = raw.charCodeAt(i + 1); m.fill(v, k, k + n); k += n; }
  const dist = new Float32Array(W * D), hi = v => v === 5 || v === 11 || v === 9 || v === 12;
  for (let i = 0; i < W * D; i++) dist[i] = hi(m[i]) ? 1e3 : 0;
  for (let z = 0; z < D; z++) for (let x = 0; x < W; x++) { const i = z * W + x; if (!dist[i]) continue; let d = dist[i]; if (x) d = Math.min(d, dist[i - 1] + 1); if (z) d = Math.min(d, dist[i - W] + 1); if (x && z) d = Math.min(d, dist[i - W - 1] + 1.41); if (z && x < W - 1) d = Math.min(d, dist[i - W + 1] + 1.41); dist[i] = d; }
  for (let z = D - 1; z >= 0; z--) for (let x = W - 1; x >= 0; x--) { const i = z * W + x; if (!dist[i]) continue; let d = dist[i]; if (x < W - 1) d = Math.min(d, dist[i + 1] + 1); if (z < D - 1) d = Math.min(d, dist[i + W] + 1); if (x < W - 1 && z < D - 1) d = Math.min(d, dist[i + W + 1] + 1.41); if (x && z < D - 1) d = Math.min(d, dist[i + W - 1] + 1.41); dist[i] = d; }
  return { m, dist };
}
export function mulberry32(a) { return function () { a |= 0; a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
function makeNoise(seed) {
  const perm = new Uint8Array(512), r = mulberry32(seed);
  for (let i = 0; i < 256; i++) perm[i] = i;
  for (let i = 255; i > 0; i--) { const j = (r() * (i + 1)) | 0; [perm[i], perm[j]] = [perm[j], perm[i]]; }
  for (let i = 0; i < 256; i++) perm[i + 256] = perm[i];
  const val = (x, z) => perm[(perm[x & 255] + z) & 511] / 255;
  const sm = t => t * t * (3 - 2 * t);
  const n2 = (x, z) => { const xi = Math.floor(x), zi = Math.floor(z), xf = sm(x - xi), zf = sm(z - zi);
    const a = val(xi, zi), b = val(xi + 1, zi), c = val(xi, zi + 1), d = val(xi + 1, zi + 1);
    return a + (b - a) * xf + (c - a) * zf + (a - b - c + d) * xf * zf; };
  return (x, z, oct = 4) => { let s = 0, amp = 1, f = 1, t = 0; for (let o = 0; o < oct; o++) { s += n2(x * f, z * f) * amp; t += amp; amp *= 0.5; f *= 2.03; } return s / t; };
}

